export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, th };

/** Fill `{name}` placeholders; unknown ones stay as written. */
export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** A coach name that already says "Coach …" / "โค้ช…" — don't add the label twice. */
export const carriesCoachLabel = (name: string) => /^\s*(coach\b|โค้ช)/i.test(name);

/** The locale a first visit gets: a stored choice, else Thai for a Thai browser, else English. */
export function initialLocale(stored: string | null, browserLanguage: string | undefined): Locale {
  if (stored === "th" || stored === "en") return stored;
  return browserLanguage?.toLowerCase().startsWith("th") ? "th" : "en";
}

/** The BCP 47 tag dates use: Thai with Gregorian years (a trainer's dates are Gregorian too). */
export const intlTag = (l: Locale) => (l === "th" ? "th-TH-u-ca-gregory" : "en-GB");
